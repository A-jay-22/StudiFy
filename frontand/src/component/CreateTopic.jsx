import { useState } from "react";
import {
  Download,
  ExternalLink,
  FileCheck2,
  FileQuestion,
  FileText,
  LoaderCircle,
  Save,
  Sparkles,
} from "lucide-react";
import { useStudy } from "../StudyContext.jsx";

const subjects = [
  "General",
  "Physics",
  "Mathematics",
  "Chemistry",
  "Biology",
  "Computer Science",
  "Geography",
  "History",
  "English",
  "Other"
];

export const CreateTopic = ({ onMockExam }) => {
  const { studyApi, saveCreatedItem, onToast } = useStudy();
  const [topic, setTopic] = useState("");
  const [subject, setSubject] = useState("General");
  const [level, setLevel] = useState("Class 10");
  const [difficulty, setDifficulty] = useState("Medium");
  const [length, setLength] = useState("Medium");
  const [includeQuestions, setIncludeQuestions] = useState(true);
  const [generated, setGenerated] = useState(null);
  const [generating, setGenerating] = useState(false);
  const [generationError, setGenerationError] = useState("");

  async function handleGenerate(event) {
    event.preventDefault();
    setGenerationError("");
    if (!topic.trim()) {
      onToast("Enter a topic to generate a study guide.", "error");
      return;
    }
    setGenerating(true);
    try {
      const result = await studyApi.generate({
        action: "topic",
        prompt: topic.trim(),
        subject,
        level,
        difficulty,
        length,
        includeQuestions,
      });
      setGenerated(result.item);
      await saveCreatedItem(result.item);
      onToast("Your AI study guide was generated and saved as a PDF!");
    } catch (error) {
      setGenerationError(error.message);
      onToast(error.message, "error");
    } finally {
      setGenerating(false);
    }
  }

  function downloadText(format = "txt") {
    if (!generated) return;
    const isMd = format === "md";
    const filename = `${generated.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.${
      isMd ? "md" : "txt"
    }`;

    const textContent = isMd
      ? `# ${generated.title}\n**Subject:** ${generated.subject}\n**Generated by Studify AI**\n\n${generated.content}`
      : `${generated.title}\nSubject: ${generated.subject}\nGenerated by Studify AI\n\n${generated.content}`;

    const blob = new Blob([textContent], {
      type: isMd ? "text/markdown;charset=utf-8" : "text/plain;charset=utf-8",
    });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = filename;
    link.click();
    URL.revokeObjectURL(url);
    onToast(`Study guide downloaded as .${isMd ? "md" : "txt"}.`);
  }

  return (
    <section className="mx-auto max-w-[1100px] page-transition">
      <header className="mb-6">
        <h1 className="font-display text-[23px] font-extrabold tracking-[-0.04em] text-[#172541]">
          Create Topic with AI
        </h1>
        <p className="mt-1 text-[12px] text-[#8291a9]">
          Generate an in-depth study guide, auto-saved as a PDF in your personal library.
        </p>
      </header>

      <form
        onSubmit={handleGenerate}
        className="rounded-2xl border border-[#e8eef8] bg-white p-5 shadow-panel sm:p-6"
      >
        <label className="block">
          <span className="mb-2 block text-[11px] font-bold text-[#77869f]">
            Topic or Syllabus Concept
          </span>
          <textarea
            value={topic}
            onChange={(event) => setTopic(event.target.value)}
            placeholder="e.g. Quantum superposition, Photosynthesis and Krebs cycle, World War I causes..."
            maxLength={8000}
            required
            rows={3}
            className="w-full resize-y rounded-xl border border-[#e5ecf7] bg-white p-3.5 text-[12px] text-[#42516c] outline-none placeholder:text-[#a0acc0] focus:border-[#aebaff] focus:ring-4 focus:ring-[#f0f2ff]"
          />
        </label>

        <div className="mt-4 grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
          {[
            ["Subject", subject, setSubject, subjects],
            [
              "Class / level",
              level,
              setLevel,
              [
                "Class 6",
                "Class 7",
                "Class 8",
                "Class 9",
                "Class 10",
                "Class 11",
                "Class 12",
                "College / University",
                "Professional / Learning",
              
              ],
            ],
            ["Difficulty", difficulty, setDifficulty, ["Easy", "Medium", "Hard"]],
            ["Length", length, setLength, ["Concise", "Medium", "Comprehensive"]],
          ].map(([label, value, setter, options]) => (
            <label key={label} className="block">
              <span className="mb-2 block text-[11px] font-bold text-[#77869f]">{label}</span>
              <select
                value={value}
                onChange={(event) => setter(event.target.value)}
                className="h-11 w-full rounded-xl border border-[#e5ecf7] bg-white px-3 text-[12px] font-semibold text-[#42516c] outline-none focus:border-[#aebaff]"
              >
                {options.map((option) => (
                  <option key={option}>{option}</option>
                ))}
              </select>
            </label>
          ))}
        </div>

        <label className="mt-4 inline-flex items-center gap-2 text-[11px] font-semibold text-[#71809a]">
          <input
            type="checkbox"
            checked={includeQuestions}
            onChange={(event) => setIncludeQuestions(event.target.checked)}
            className="h-4 w-4 rounded accent-[#4d5ef0]"
          />
          Include revision practice questions and answers
        </label>

        {generationError && (
          <p
            role="alert"
            className="mt-4 rounded-xl border border-[#ffd4d7] bg-[#fff5f5] px-4 py-3 text-xs leading-5 text-[#a93440]"
          >
            {generationError}
          </p>
        )}

        <button
          type="submit"
          disabled={generating}
          className="mt-5 inline-flex min-h-11 w-full items-center justify-center gap-2 rounded-xl bg-[#5146ed] px-6 text-[12px] font-bold text-white shadow-md hover:bg-[#4035dc] disabled:opacity-60 transition sm:w-auto"
        >
          {generating ? <LoaderCircle size={15} className="animate-spin" /> : <Sparkles size={15} />}
          {generating ? "Generating and saving as PDF…" : "Generate Topic (Save as PDF)"}
        </button>
      </form>

      {generating && (
        <div className="mt-6 rounded-2xl border border-blue-100 bg-white p-6 shadow-panel animate-fade-in space-y-4">
          <div className="flex items-center gap-3">
            <span className="h-4 w-4 rounded-full bg-blue-600 animate-ping" />
            <span className="text-xs font-bold text-blue-700">Gemini AI is crafting your structured study guide &amp; generating PDF…</span>
          </div>
          <div className="h-6 w-2/3 rounded-xl skeleton-shimmer" />
          <div className="space-y-2.5">
            <div className="h-4 w-full rounded-lg skeleton-shimmer" />
            <div className="h-4 w-5/6 rounded-lg skeleton-shimmer" />
            <div className="h-4 w-4/6 rounded-lg skeleton-shimmer" />
          </div>
        </div>
      )}

      {generated && (
        <article className="mt-6 rounded-2xl border border-[#e8eef8] bg-white p-5 shadow-panel sm:p-7 animate-fade-in-up hover-card-lift">
          <header className="flex flex-wrap items-start justify-between gap-3 border-b border-gray-100 pb-4">
            <div>
              <p className="text-[10px] font-bold uppercase tracking-[0.12em] text-[#8291a9]">
                {generated.subject} · {level} · {difficulty}
              </p>
              <h2 className="mt-1 font-display text-xl font-bold text-[#263550]">
                {generated.title}
              </h2>
              <div className="mt-2 flex items-center gap-2">
                <span className="inline-flex items-center gap-1 rounded-md bg-emerald-50 px-2.5 py-1 text-[11px] font-bold text-emerald-700">
                  <FileCheck2 size={13} /> Saved as PDF in your library
                </span>
              </div>
            </div>

            <div className="flex flex-wrap items-center gap-2">
              {/* Primary PDF Download */}
              <a
                href={studyApi.downloadUrl(generated._id, "pdf")}
                download
                onClick={() => onToast("Downloading study guide as PDF...")}
                className="inline-flex items-center gap-1.5 rounded-xl bg-gradient-to-r from-rose-600 to-rose-700 px-4 py-2 text-xs font-bold text-white shadow-md hover:brightness-110 transition"
              >
                <Download size={14} /> Download PDF
              </a>

              {/* View PDF inline */}
              <a
                href={studyApi.viewPdfUrl(generated._id)}
                target="_blank"
                rel="noreferrer"
                className="inline-flex items-center gap-1 rounded-xl border border-gray-200 bg-white px-3 py-2 text-xs font-semibold text-gray-700 hover:bg-gray-50 transition"
                title="Open PDF in new tab"
              >
                <ExternalLink size={13} /> View PDF
              </a>

              {onMockExam && (
                <button
                  type="button"
                  onClick={() => onMockExam(generated)}
                  className="inline-flex items-center gap-1.5 rounded-xl bg-indigo-50 px-3 py-2 text-xs font-bold text-indigo-600 hover:bg-indigo-100 transition"
                >
                  <FileQuestion size={13} /> Test Knowledge
                </button>
              )}

              <button
                type="button"
                onClick={() => downloadText("txt")}
                className="inline-flex items-center gap-1 rounded-lg bg-gray-100 px-2.5 py-2 text-xs font-semibold text-gray-600 hover:bg-gray-200 transition"
              >
                <Download size={12} /> .TXT
              </button>

              <button
                type="button"
                onClick={() => downloadText("md")}
                className="inline-flex items-center gap-1 rounded-lg bg-gray-100 px-2.5 py-2 text-xs font-semibold text-gray-600 hover:bg-gray-200 transition"
              >
                <Download size={12} /> .MD
              </button>
            </div>
          </header>

          <div className="mt-5 whitespace-pre-wrap text-[13px] leading-7 text-[#455571]">
            {generated.content}
          </div>
        </article>
      )}
    </section>
  );
}

export default CreateTopic;
